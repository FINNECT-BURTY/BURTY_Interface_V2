-- 기기 신뢰 토큰의 평문 컬럼을 없앤다 (#158)
--
-- 신뢰 기기는 토큰의 해시(device_token_hash)로 찾는다. 같은 행에 평문(device_token)을
-- 두면 해시로 저장한 의미가 없다 — DB 가 읽히는 순간 모든 기기 토큰이 그대로 드러난다.
--
-- 평문을 쓰던 곳은 둘이었다.
--   1. 같은 기기가 다시 등록할 때 저장해 둔 평문을 돌려줬다 → 이제 새 토큰을 발급한다
--   2. 푸시 발송 대상으로 썼다 → 그 자체가 결함이었다 (#156), 이제 fcm_token 만 쓴다
--
-- 되돌리지 않는다. 지워진 평문은 복구할 방법도, 복구할 이유도 없다.
-- 이미 발급된 토큰은 해시가 남아 있으므로 계속 통한다.

ALTER TABLE tbl_device
    DROP COLUMN IF EXISTS device_token;
